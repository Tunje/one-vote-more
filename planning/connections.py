"""Lists every open connection: each place in game/ that still calls the removed economy. usage: python connections.py REPO OUT.md"""
import collections
import io
import os
import re
import subprocess
import sys

repo, out = sys.argv[1], sys.argv[2]
files = subprocess.run(["git", "ls-tree", "-r", "--name-only", "785c72f", "game/sim/economy", "game/sim/companies"], cwd=repo, capture_output=True, text=True).stdout.split("\n")
classes = {}   # class name -> file
preload_names = {}
for f in files:
    if not f.endswith(".gd"):
        continue
    src = subprocess.run(["git", "show", "785c72f:" + f], cwd=repo, capture_output=True, text=True, encoding="utf-8", errors="replace").stdout
    m = re.search(r"^class_name (\w+)", src, re.M)
    if m:
        classes[m.group(1)] = f.replace("game/sim/", "")
pat = re.compile(r"\b(%s)\.(\w+)" % "|".join(sorted(classes, key=len, reverse=True)))
pat_bare = re.compile(r"\b(%s)\b" % "|".join(sorted(classes, key=len, reverse=True)))
pat_path = re.compile(r"res://sim/(economy|companies)/(\w+)\.gd")
AREAS = [("sim/politics", "Politics"), ("sim/law", "Law and justice"), ("sim/staff", "Staff"), ("sim/media", "The press"), ("sim/office", "The office and decision desk"),
         ("sim/planet", "The planet"), ("sim/population", "Population"), ("sim/transport", "Roads, town grid, map layout"), ("sim/waste", "Waste map"),
         ("sim/core", "Core"), ("ui", "Screens"), ("tools", "Tools"), ("tests", "Tests")]
rows = collections.defaultdict(list)       # area -> [(file, line, text, [targets])]
by_target = collections.Counter()
by_target_area = collections.defaultdict(collections.Counter)
g = os.path.join(repo, "game")
for root, _, fs in os.walk(g):
    if ".godot" in root:
        continue
    for fn in sorted(fs):
        if not fn.endswith(".gd"):
            continue
        rel = os.path.relpath(os.path.join(root, fn), g).replace("\\", "/")
        area = next((a for a, _ in AREAS if rel.startswith(a + "/") or rel == a), "other")
        for i, line in enumerate(io.open(os.path.join(root, fn), encoding="utf-8", errors="replace"), 1):
            code = line.split("#", 1)[0] if not line.lstrip().startswith("#") else ""
            t = ["%s.%s" % (m.group(1), m.group(2)) for m in pat.finditer(code)]
            t += ["file %s/%s.gd" % (m.group(1), m.group(2)) for m in pat_path.finditer(code)]
            if not t and pat_bare.search(code):
                t = [m.group(1) for m in pat_bare.finditer(code)]
            if not t:
                continue
            rows[area].append((rel, i, line.strip()[:170], t))
            for x in t:
                by_target[x] += 1
                by_target_area[x][area] += 1
o = io.open(out, "w", encoding="utf-8", newline="\n")
w = o.write
w("# Open connections to the removed economy\n\n")
w("The economy (`sim/economy`, `sim/companies` and the economy's tests: 35,129 lines) was cut out of `game/` on 2026-11-17 on the user's order. "
  "Nothing else was changed, so every call into it is left open. This file lists every one of them, generated by `connections.py` from the code as it stands. "
  "The game does not compile until these are connected again. The game as it was before the cut is `game_full_copy/` and commit 785c72f.\n\n")
total = sum(len(v) for v in rows.values())
core = sum(len(rows[a]) for a, _ in AREAS if a not in ("tools", "tests"))
w("**%d lines** call the removed economy: **%d in the game and its screens**, %d in tools, %d in tests.\n\n" % (total, core, len(rows["tools"]), len(rows["tests"])))
w("## 1. Who needs the economy\n\n| Part of the game | Files | Lines |\n|---|---|---|\n")
for a, name in AREAS:
    if rows[a]:
        w("| %s (`%s`) | %d | %d |\n" % (name, a, len({r[0] for r in rows[a]}), len(rows[a])))
w("\n## 2. What they ask the economy for\n\nCounted in the game and its screens only (tools and tests left out). The file is where it lived in the old economy.\n\n")
groups = collections.defaultdict(list)
for x, n in by_target.items():
    n2 = sum(c for a, c in by_target_area[x].items() if a not in ("tools", "tests"))
    if n2:
        cls = x.split(".")[0] if not x.startswith("file ") else x
        groups[cls].append((n2, x, by_target_area[x]))
order = sorted(groups, key=lambda c: -sum(n for n, _, _ in groups[c]))
w("| Old economy part | Was in | Calls | Asked for (calls) |\n|---|---|---|---|\n")
for c in order:
    items = sorted(groups[c], reverse=True)
    w("| `%s` | %s | %d | %s |\n" % (c, classes.get(c, ""), sum(n for n, _, _ in items), ", ".join("`%s` %d" % (x.split(".", 1)[1] if "." in x and not x.startswith("file ") else x, n) for n, x, _ in items)))
w("\n## 3. Every open connection, by part of the game\n\n")
for a, name in AREAS:
    if not rows[a] or a in ("tools", "tests"):
        continue
    w("### %s\n\n" % name)
    cur = None
    for rel, i, text, t in rows[a]:
        if rel != cur:
            cur = rel
            w("\n**`%s`** (%d)\n\n" % (rel, sum(1 for r in rows[a] if r[0] == rel)))
        w("- line %d: `%s`\n" % (i, text.replace("`", "'")))
    w("\n")
w("## 4. Tools and tests\n\nThese are not connections of the game itself. Listed by file with the number of lines that call the economy.\n\n")
for a in ("tools", "tests"):
    c = collections.Counter(r[0] for r in rows[a])
    w("**%s** (%d files): %s\n\n" % (a, len(c), ", ".join("`%s` %d" % (f.split("/", 1)[1], n) for f, n in sorted(c.items()))))
o.close()
print(total, "lines;", core, "in game and screens;", len(classes), "classes")
